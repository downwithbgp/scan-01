def strips_for(width, rows):
    """4 strips of 8 rows; bit r (0 = top of strip) = pixel at row r."""
    out = []
    for s in range(4):
        strip = []
        for x in range(width):
            byte = 0
            for r in range(8):
                if rows[s * 8 + r][x] == "#":
                    byte |= 1 << r
            strip.append(byte)
        out.append(strip)
    return out

def emit():
    print("/* Auto-generated by tools/fontgen_racing.py — do not edit by hand. */")
    print("/* Scan 01 racing-digits font (vision §5.6): 36 glyphs, 32 px tall. */")
    print("#include \"font_racing.h\"")
    print()
    print("const RacingGlyph_t gRacingGlyphs[36] = {")
    for name in sorted(GLYPHS.keys()):
        width, rows = GLYPHS[name]
        strips = strips_for(width, rows)
        print(f"    /* {name} (w={width}) */")
        print("    { %d, {" % width)
        for s in range(4):
            print("        { " + ", ".join(f"0x{b:02X}" for b in strips[s]) + " },")
        print("    } },")
    print("};")
    print()
    print("const char gRacingGlyphOrder[] = \"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ\";")
    print()
    print("const uint8_t gRacingGlyphAdvance[36] = {")
    advances = []
    for ch in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        width, _ = GLYPHS[ch]
        advances.append(str(width))
    print("    " + ", ".join(advances) + ",")
    print("};")

if __name__ == "__main__":
    emit()
